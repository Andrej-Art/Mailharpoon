export type PixelIconName = keyof typeof ICONS;

export function PixelIcon({ name, size = 40, className }: { name: PixelIconName; size?: number; className?: string }) {
  const rows = ICONS[name];
  const rects: { x: number; y: number; accent: boolean }[] = [];
  rows.forEach((row, y) => [...row].forEach((c, x) => c !== "." && rects.push({ x, y, accent: c === "o" })));
  return (
    <svg viewBox="0 0 16 16" width={size} height={size} shapeRendering="crispEdges" className={className} aria-hidden>
      {rects.map((r) => (
        <rect key={`${r.x}-${r.y}`} x={r.x} y={r.y} width="1" height="1" fill={r.accent ? "var(--color-harpoon)" : "currentColor"} />
      ))}
    </svg>
  );
}
